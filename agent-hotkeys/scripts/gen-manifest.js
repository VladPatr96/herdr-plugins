#!/usr/bin/env node
'use strict';

// Regenerates herdr-plugin.toml so its focus actions always match lib/hotkeys.js KEYS.
// Usage: node scripts/gen-manifest.js

const fs = require('node:fs');
const path = require('node:path');
const { KEYS, keyLabel } = require('../lib/hotkeys');
const pkg = require('../package.json');

const EVENTS = [
  'pane.created',
  'pane.agent_detected',
  'pane.agent_status_changed', // an agent leaving its pane shows up here
  'pane.exited',
  'pane.closed',
  'pane.moved',
  'tab.closed',
  'workspace.closed',
];

let toml = `# Generated by scripts/gen-manifest.js; edit that script, not this file.
id = "vladpatr96.agent-hotkeys"
name = "Agent Hotkeys"
version = "${pkg.version}"
min_herdr_version = "0.8.2"
description = "${pkg.description}"
platforms = ["linux", "macos", "windows"]

# Token metadata is not restored after a server restart, so label again on start.
[[startup]]
command = ["node", "bin/sync.js"]

# Manual resync; also needed right after \`herdr plugin link\`, which runs no startup hooks.
[[actions]]
id = "sync"
title = "Agent Hotkeys: sync labels"
contexts = ["workspace", "global"]
command = ["node", "bin/sync.js"]
`;

for (const on of EVENTS) {
  toml += `\n[[events]]\non = "${on}"\ncommand = ["node", "bin/sync.js"]\n`;
}

toml += '\n# One focus action per hotkey slot; `node bin/keys.js` prints the key bindings.\n';
KEYS.forEach((key, i) => {
  toml += `\n[[actions]]\nid = "focus-${i + 1}"\ntitle = "Agent Hotkeys: focus ${keyLabel(key)}"\ncontexts = ["workspace", "global"]\ncommand = ["node", "bin/focus.js", "${i + 1}"]\n`;
});

fs.writeFileSync(path.join(__dirname, '..', 'herdr-plugin.toml'), toml);
process.stdout.write(`herdr-plugin.toml: ${EVENTS.length} events, ${KEYS.length} focus actions\n`);
