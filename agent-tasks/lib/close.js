'use strict';

// Закрыть агента из списка: что именно для этого сделать.
//
// «Закрыть» здесь значит закрыть его вкладку — сессия агента завершается, а не
// прячется. Поэтому у живого агента сначала спрашивают, и только ответ `y`
// доводит дело до конца: промахнуться по клавише рядом с `x` легко, а вернуть
// сессию нельзя.
//
// Закрывается вкладка, а не панель: плагин заводит агенту вкладку целиком, и
// оставлять от неё пустую оболочку незачем. Вкладку называет строка списка, и
// она там живая — панель агента могла с запуска переехать.
//
// Исключение — агент, которого показывают под списком: он стоит во вкладке
// самой доски, и закрывать её нельзя. У него уходит только панель.
//
// Файл задачи с планом остаётся на диске нарочно: по нему видно, чем кончилось.
// Из реестра запись уходит сразу, не дожидаясь `sync`, чтобы список ответил на
// нажатие, а не через секунду.
//
// Здесь только решение; сами команды herdr выполняет `bin/board.js`.

const NOTHING = { confirm: false, question: null, closeTab: null, closePane: null, forget: null, release: false };

function closePlan({ row = null, confirmed = false, borrowed = null, boardTab = null } = {}) {
  if (!row) return { ...NOTHING };

  // Панели уже нет: закрывать нечего, остаётся вычеркнуть строку. Спрашивать
  // об этом — притворяться, будто на кону что-то есть.
  if (row.status === 'gone') {
    return { ...NOTHING, forget: row.paneId };
  }

  if (!confirmed) {
    return { ...NOTHING, confirm: true, question: `Закрыть «${row.title}»? y — да, любая другая — нет` };
  }

  // Агент, показанный под списком, стоит во вкладке самой доски. Закрыть её —
  // закрыть вместе с ним и список, из которого закрывают. Тогда уходит только
  // его панель, а вкладка остаётся доске.
  const ownTab = Boolean(row.tabId) && row.tabId !== boardTab;

  return {
    confirm: false,
    question: null,
    closeTab: ownTab ? row.tabId : null,
    closePane: ownTab ? null : row.paneId,
    forget: row.paneId,
    // Одолженная панель стоит во вкладке списка. Забыть об этом до закрытия —
    // значит потом искать, куда вернуть то, чего уже нет.
    release: Boolean(borrowed && borrowed.paneId === row.paneId),
  };
}

module.exports = { closePlan };
